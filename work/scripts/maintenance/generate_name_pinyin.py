"""Generate identical offline character readings for both clients (no runtime dependency)."""
from collections import defaultdict
from pathlib import Path
import hashlib
import json
import unicodedata
import urllib.request

ROOT = Path(__file__).resolve().parents[3]
REVISION = '9d05c9e29cb6a7e5c79f2f5279f5c1014246a19a'
cache = ROOT / 'work/builds/name-sort-data'
cache.mkdir(parents=True, exist_ok=True)
for name in ('pinyin.txt', 'LICENSE'):
    path = cache / name
    if not path.exists():
        url = f'https://raw.githubusercontent.com/mozillazg/pinyin-data/{REVISION}/{name}'
        with urllib.request.urlopen(url, timeout=30) as response:
            path.write_bytes(response.read())
data = (cache / 'pinyin.txt').read_bytes()
assert hashlib.sha256(data).hexdigest() == '90c11bd680ccfe7f2617a6e25abdb1fb87b5540df3e6f011ca50aaf3c7263a89'
groups = defaultdict(list)
for line in data.decode('utf-8').splitlines():
    if not line.startswith('U+'):
        continue
    code, readings = line.split(':', 1)
    reading = readings.split('#')[0].strip().split(',')[0]
    # Keep syllable boundaries; ignore tones; use v for the umlaut vowel.
    reading = unicodedata.normalize('NFD', reading).replace('u\u0308', 'v')
    reading = ''.join(c for c in reading if not unicodedata.combining(c))
    assert reading.isascii() and reading.isalpha(), reading
    groups[reading].append(chr(int(code[2:], 16)))
rows = [reading + '\t' + ''.join(chars) for reading, chars in sorted(groups.items())]
license_text = (cache / 'LICENSE').read_text('utf-8')
header = (f'Generated by work/scripts/maintenance/generate_name_pinyin.py.\n'
          f'Source: https://github.com/mozillazg/pinyin-data/tree/{REVISION}\n'
          f'pinyin.txt SHA256: {hashlib.sha256(data).hexdigest()}\n'
          'First listed reading per character, no tones, umlaut u = v.\n\n' + license_text)
python = '\n'.join(('# ' + line).rstrip() for line in header.splitlines()) + '\nGROUPS = (\n'
python += ''.join('    ' + repr(row) + ',\n' for row in rows) + ')\n'
java = '/*\n' + header + '\n*/\npackage app.jmbatch.android;\n\n'
java += 'final class NamePinyinData {\n    static final String[] GROUPS = {\n'
java += ''.join('        ' + json.dumps(row, ensure_ascii=False) + ',\n' for row in rows)
java += '    };\n    private NamePinyinData() {}\n}\n'
(ROOT / 'work/jmbatch/name_pinyin.py').write_text(python, encoding='utf-8')
(ROOT / 'work/jmbatch-android/app/src/main/java/app/jmbatch/android/NamePinyinData.java').write_text(java, encoding='utf-8')
for path in (ROOT / 'work/jmbatch/THIRD_PARTY_LICENSES/pinyin-data/LICENSE.txt',
             ROOT / 'work/jmbatch-android/app/src/main/assets/pinyin-data-LICENSE.txt'):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(header, encoding='utf-8')
print(f'Generated {len(rows)} readings for {sum(map(len, groups.values()))} characters.')
